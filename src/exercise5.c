#include <stdio.h>

int main(int argc, char** argv) {

    float arr1[10][3] = {
        {3, 4.5, 5}, // 1
        {3, 4.5, 5}, // 2
        {3, 4.5, 5}, // 3
        {3, 4.5, 5}, // 4
        {3, 4.5, 5}, // 5
        {3, 4.5, 5}, // 6
        {3, 4.5, 5}, // 7
        {3, 4.5, 5}, // 8
        {3, 4.5, 5}, // 9
        {3, 4.5, 5} // 10
    };

    float arr2[3][10] = {
        {6, 7.8, 8, 0, 5.23, 4, 2, 1.33, 34, 7.1},
        {6, 7.8, 8, 0, 5.23, 4, 2, 1.33, 34, 7.1},
        {6, 7.8, 8, 0, 5.23, 4, 2, 1.33, 34, 7.1}
    };

    float result[10][10];

    for(int i = 0; i < 10; i++){
        for(int j = 0; j < 10; j++){
            result[i][j] = 0;
            for(int m = 0; m < 3; m++){
                result[i][j] += arr1[i][m] * arr2[m][j];
            }
        }
    }

    for (int i = 0; i < 10; i++) {
        for (int j = 0; j < 10; j++) {
            printf("%.2f", result[i][j]);
            if (i != 10 - 1 || j != 10 - 1) {
                printf(" ");
            }
        }
    }
    printf("\n");
}